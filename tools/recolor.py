#!/usr/bin/env python3
"""KING_RECOLOR (Nov 22): build ui2-recolor.css from style.css. Every generic rule that hard-codes the old KAIROS colors
(mint green, pink-red, purple, amber, sky blue) gets a copy scoped to the new look (body.ui2-iv) using the theme's variables,
so Ivory/Onyx and every theme recolor the whole app. Run: python3 tools/recolor.py"""
import re, tinycss2, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FAM = {
 "up":   (["#2bd4a0", "#3ddc84", "#21b98a", "#38e0ae", "#26a69a", "#5ee6b8"], ["43,212,160", "61,220,132", "33,185,138"]),
 "dn":   (["#ff4d5e", "#ff6b7a", "#ff5d6c", "#e9505f", "#ff7e8b", "#ef5350"], ["255,77,94", "255,107,122", "255,93,108", "233,80,95"]),
 "ink":  (["#a78bfa", "#7c3aed", "#8b5cf6", "#c08bff", "#7c6bff", "#c4b5fd"], ["167,139,250", "124,107,255", "139,92,246", "124,58,237", "192,139,255"]),
 "warn": (["#ffc65c", "#ffb547"], ["255,198,92", "255,181,71"]),
 "blue": (["#7aa7ff", "#3d8bff", "#2962ff", "#3b82f6"], ["122,167,255", "61,139,255", "10,132,255", "59,130,246"]),
}
VAR = {"up": "var(--up)", "dn": "var(--dn)", "ink": "var(--ink)", "warn": "var(--warn)", "blue": "var(--blue,#2f6fdb)"}
def recolor(v):
    out, hit = v, False
    for k, (hexes, rgbs) in FAM.items():
        for h in hexes:
            if re.search(re.escape(h) + r"(?![0-9a-f])", out, re.I): out = re.sub(re.escape(h) + r"(?![0-9a-f])", VAR[k], out, flags=re.I); hit = True
        for r in rgbs:
            pat = r"rgba\(\s*" + r"\s*,\s*".join(r.split(",")) + r"\s*,\s*([0-9.]+)\s*\)"
            if re.search(pat, out):
                out = re.sub(pat, lambda m: "color-mix(in srgb,%s %d%%,transparent)" % (VAR[k], round(float(m.group(1)) * 100)), out); hit = True
    return out, hit
SKIP = re.compile(r"body\.(?!ui2\b)|\.waifu|skin-|\.pix\b|\[data-pxt|\.light\b|\.blind|\.glass")
def scope(sel):
    parts = []
    for s in sel.split(","):
        s = s.strip()
        if not s or SKIP.search(s): continue
        if s.startswith(("html", ":root")): continue
        if s.startswith("body"): s = s[4:].lstrip()
        parts.append("body.ui2-iv " + s if s else "body.ui2-iv")
    return ",".join(parts)
def rules(nodes, depth=0):
    out = []
    for n in nodes:
        if n.type == "qualified-rule":
            sel = tinycss2.serialize(n.prelude).strip(); sc = scope(sel)
            if not sc: continue
            decls = tinycss2.parse_declaration_list(n.content, skip_whitespace=True, skip_comments=True)
            keep = []
            for d in decls:
                if d.type != "declaration": continue
                val = tinycss2.serialize(d.value).strip(); nv, hit = recolor(val)
                if hit: keep.append("%s:%s%s" % (d.name, nv, " !important" if d.important else ""))
            if keep: out.append("%s{%s}" % (sc, ";".join(keep)))
        elif n.type == "at-rule" and n.lower_at_keyword == "media" and n.content:
            inner = rules(tinycss2.parse_rule_list(n.content, skip_whitespace=True, skip_comments=True), depth + 1)
            if inner: out.append("@media %s{%s}" % (tinycss2.serialize(n.prelude).strip(), "".join(inner)))
    return out
src = open(os.path.join(ROOT, "style.css")).read()
out = rules(tinycss2.parse_stylesheet(src, skip_whitespace=True, skip_comments=True))
open(os.path.join(ROOT, "ui2-recolor.css"), "w").write("/* GENERATED by tools/recolor.py (KING_RECOLOR) - do not edit by hand */\n" + "\n".join(out) + "\n")
print(len(out), "rules")
